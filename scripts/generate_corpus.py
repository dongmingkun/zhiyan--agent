def build_text(section, keywords, content):
    kw = " ".join(keywords)
    # 关键词重复三遍 + 正文，与线上现有格式一致
    return f"{section} {kw} {kw} {kw} {content}"


def main():
    # 读取现有语料（保留原 52 条）
    existing = []
    if os.path.exists(CORPUS_PATH):
        with open(CORPUS_PATH, "r", encoding="utf-8") as f:
            data = json.load(f)
        existing = data.get("passages", [])
        if not existing:
            # 目标文件存在却读不到任何条目 → 说明读错了路径或文件被损坏。
            # 此时继续写库会把线上 200+ 条语料静默覆盖成只有 NEW_PASSAGES 的残缺版本，
            # 因此直接报错退出，宁可失败也不产出残缺数据。
            raise SystemExit(
                f"[generate_corpus] 错误：{CORPUS_PATH} 存在但 passages 为空，"
                f"疑似读错路径或文件损坏，已中止（不覆盖原文件）。"
            )
    exist_ids = {p.get("id") for p in existing}

    merged = list(existing)
    added = 0
    for p in NEW_PASSAGES:
        if p["id"] in exist_ids:
            # 跳过重复 id，避免覆盖既有精心编写内容
            continue
        content = p["content"]
        merged.append({
            "id": p["id"],
            "chapter": p["chapter"],
            "section": p["section"],
            "keywords": p["keywords"],
            "source": f"{p['chapter']} · {p['section']}",
            "text": build_text(p["section"], p["keywords"], content),
            "content": content,
        })
        exist_ids.add(p["id"])
        added += 1

    # 原子写：先写临时文件，成功后再 os.replace 覆盖，避免中途异常留下半截 JSON
    os.makedirs(DATA_DIR, exist_ok=True)
    tmp_path = CORPUS_PATH + ".tmp"
    with open(tmp_path, "w", encoding="utf-8") as f:
        json.dump({"passages": merged}, f, ensure_ascii=False, indent=2)
    os.replace(tmp_path, CORPUS_PATH)

    from collections import Counter
    chapters = Counter(p["chapter"] for p in merged)
    print(f"原有条目: {len(existing)}，本次新增: {added}，合计: {len(merged)}")
    for ch, n in chapters.items():
        print(f"  {n:3d}  {ch}")


if __name__ == "__main__":
    main()
